"""Tests for multiqc_versions.py: the tool versions of the MultiQC report.

A version the tool wrote into its own output must win over the pinned version,
and a pinned version must always carry the "(workflow pin)" label. The expected
pins are read from workflow/envs/ by the script's own reader, so these tests do
not break when a pin is updated.

Run: pytest workflow/scripts/90_report/test_multiqc_versions.py -q
"""

import json
from pathlib import Path

import pytest
import yaml

import multiqc_versions as versions


ENV_DIR = Path(__file__).resolve().parents[2] / "envs"


def pinned(environment, package):
    """The label the script gives a version taken from the environment files."""
    return versions.configured_version(ENV_DIR, environment, package) + " (workflow pin)"


def test_observed_version_wins_over_current_recipe(tmp_path):
    log = tmp_path / "03.taxonomy" / "S1" / "gtdbtk.log"
    log.parent.mkdir(parents=True)
    log.write_text("INFO: GTDB-Tk v2.6.1\n")
    values = versions.collect_versions(ENV_DIR, tmp_path, ["S1"])
    assert values["GTDB-Tk"] == ["2.6.1"]
    # CheckM writes no version into its output, so the pin is shown, labelled.
    assert values["CheckM"] == [pinned("checkm", "checkm-genome")]


def test_all_recorded_versions_are_retained_and_unselected_samples_ignored(tmp_path):
    for sample, version in (("S1", "1.0.1"), ("S2", "0.24.0"), ("OLD", "0.19.0")):
        path = tmp_path / "01.reads" / sample / "illumina" / f"{sample}_fastp.json"
        path.parent.mkdir(parents=True)
        path.write_text(json.dumps({"summary": {"fastp_version": version}}))
    values = versions.collect_versions(ENV_DIR, tmp_path, ["S1", "S2"], short_reads=True)
    assert values["fastp"] == ["0.24.0", "1.0.1"]


@pytest.mark.parametrize("short_reads,long_reads,expected", [
    (False, False, set()),
    (True, False, {"fastp", "QualiMap"}),
    (False, True, {"NanoPlot", "QualiMap"}),
    (True, True, {"fastp", "NanoPlot", "QualiMap"}),
])
def test_only_mode_relevant_tools_are_added(tmp_path, short_reads, long_reads, expected):
    values = versions.collect_versions(ENV_DIR, tmp_path, ["S1"], short_reads, long_reads)
    assert set(values) - {"QUAST", "CheckM", "GTDB-Tk", "Bakta", "MultiQC"} == expected


def test_trait_tools_share_yaml_group_without_overwriting(tmp_path):
    output = tmp_path / "versions.yaml"
    versions.main(["--env-dir", str(ENV_DIR), "--output-root", str(tmp_path),
                   "--samples", "S1", "--traits", "--out", str(output)])
    config = yaml.safe_load(output.read_text())
    group = config["software_versions"]["Trait profile"]
    assert group["Baktfold"] == [pinned("baktfold", "baktfold")]
    assert group["Foldseek"] == [pinned("baktfold", "foldseek")]
    # Only the versions: nothing else is added to the top of the report.
    assert set(config) == {"software_versions"}


def test_versions_like_one_point_ten_remain_strings(tmp_path):
    (tmp_path / "tool.yaml").write_text("dependencies:\n  - tool=1.10\n")
    assert versions.configured_version(tmp_path, "tool", "tool") == "1.10"


def test_real_nanoplot_filename_and_qualimap_banner_are_recognised(tmp_path):
    nanoplot = tmp_path / "01.reads/S1/ont/raw_qc/S1_NanoPlot_20260722_1834.log"
    qualimap = tmp_path / "02.assembly/S1/eval/qualimap/qualimapReport.html"
    nanoplot.parent.mkdir(parents=True)
    qualimap.parent.mkdir(parents=True)
    nanoplot.write_text("INFO NanoPlot 1.47.1\n")
    qualimap.write_text("<p>Generated by QualiMap v.2.3</p>")
    assert versions.observed_versions(tmp_path, ["S1"], "NanoPlot") == ["1.47.1"]
    assert versions.observed_versions(tmp_path, ["S1"], "QualiMap") == ["2.3"]
    output = tmp_path / "versions.yaml"
    versions.main(["--env-dir", str(ENV_DIR), "--output-root", str(tmp_path),
                   "--samples", "S1", "--long-reads", "--out", str(output)])
    config = yaml.safe_load(output.read_text())
    assert config["software_versions"]["QualiMap"] == {"BamQC": ["2.3"]}
